// Exports the real Second Opinion engine output for both synthetic samples into a static file the
// design-lab prototypes share. Read-only use of lib/; nothing in the app is changed.
import { writeFileSync } from "node:fs";
import { analyzeBill, ENGINE_VERSION, LEVEL_LABEL } from "../../lib/analysis.ts";
import { getSample } from "../../lib/samples.ts";
import { lookupCode } from "../../lib/glossary.ts";
import { composeLetter, DEFAULT_OPTIONS } from "../../lib/letter.ts";

const today = "2026-10-30";
const cases: Record<string, unknown> = {};
for (const id of ["emergency-visit", "three-night-stay"]) {
  const bill = getSample(id)!;
  const analysis = analyzeBill(bill);
  const lines = bill.lineItems.map(line => ({ ...line, plainName: lookupCode(line.code)?.name ?? null, codeSystem: lookupCode(line.code)?.system ?? null, codeNote: lookupCode(line.code)?.plain ?? null }));
  const letter = composeLetter({ bill, findings: analysis.findings, sender: { name: "Jordan Avery", address: "", phone: "", email: "" }, options: DEFAULT_OPTIONS, today });
  cases[id] = { bill: { ...bill, lineItems: lines }, analysis, letter };
}
const out = `// Generated by shared/export-case.ts from the real engine ${ENGINE_VERSION}. Synthetic data only.\nwindow.SO = ${JSON.stringify({ engine: ENGINE_VERSION, levelLabel: LEVEL_LABEL, today, cases }, null, 1)};\n`;
writeFileSync(new URL("./case.js", import.meta.url), out);
console.log("wrote case.js");
